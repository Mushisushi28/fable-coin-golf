#!/usr/bin/env python3
"""Generate GamePatched.cs from YOUR OWN decompiled FabMob/Game.cs.

The game's entry point (FabMob.dll's `Game` class) is the one decompiled
file the port cannot compile as-is against MonoGame on Android. The
scaffold therefore compiles a patched copy, and this script produces
that copy from your own decompiled source — the patched file itself is
copyrighted game code and is never distributed with this repository.

Exactly two changes are made (this is the complete list):

1. `Environment.DeviceType` is fully qualified to
   `Microsoft.Devices.Environment.DeviceType`. The decompiled file has
   `using Microsoft.Devices;` alongside framework namespaces that also
   expose an `Environment`, which makes the bare name ambiguous under
   the Android reference pack.

2. The WP7 `protected override void OnExiting(object sender,
   EventArgs args)` becomes a plain `protected void OnExiting(...)`
   and its `base.OnExiting(sender, args);` call is removed:
   MonoGame.Framework.Android's Game has no virtual OnExiting with that
   signature to override. The method body (which forwards to the game's
   own state-preservation logic) is otherwise untouched.

Usage: apply_game_patch.py <decompiled/FabMob/Game.cs> <output GamePatched.cs>

The script verifies both patterns before writing anything. If your
decompiled file does not match the expected shape (different game
build, different decompiler settings), it refuses and tells you which
change to apply by hand — see patches/PATCHES.md, item P1.
"""
import re
import sys

HEADER = ("// GamePatched.cs — generated by patcher/apply_game_patch.py from\n"
          "// your own decompiled FabMob/Game.cs. Changes: OnExiting override\n"
          "// removed (plain method, no base call) + Environment.DeviceType\n"
          "// fully qualified. Do not redistribute this file.\n")


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 2
    src_path, out_path = argv[1], argv[2]
    text = open(src_path, encoding="utf-8-sig").read()

    # Change 1: fully qualify Environment.DeviceType (only bare uses).
    text, n1 = re.subn(r"(?<!Microsoft\.Devices\.)\bEnvironment\.DeviceType\b",
                       "Microsoft.Devices.Environment.DeviceType", text)
    if n1 == 0:
        print("FAIL: no bare 'Environment.DeviceType' found — "
              "apply change 1 by hand (patches/PATCHES.md, P1).")
        return 1

    # Change 2a: drop the override keyword on OnExiting.
    text, n2 = re.subn(r"protected\s+override\s+void\s+OnExiting\s*\(",
                       "protected void OnExiting(", text)
    if n2 != 1:
        print(f"FAIL: expected exactly 1 'protected override void OnExiting', "
              f"found {n2} — apply change 2 by hand (patches/PATCHES.md, P1).")
        return 1

    # Change 2b: remove the base.OnExiting call inside it.
    text, n3 = re.subn(r"\n[ \t]*base\.OnExiting\(sender, args\);", "", text)
    if n3 != 1:
        print(f"FAIL: expected exactly 1 'base.OnExiting(sender, args);' call, "
              f"found {n3} — apply change 2 by hand (patches/PATCHES.md, P1).")
        return 1

    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(HEADER + text)
    print(f"OK: wrote {out_path} "
          f"(DeviceType qualified x{n1}, OnExiting de-overridden, base call removed)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
